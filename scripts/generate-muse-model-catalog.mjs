/**
 * Generates the server-side (Deno/Edge) video-model catalog used by the
 * AdTool Agent (Meta Muse) tool layer.
 *
 * Source of truth stays `src/config/videoModelSpecs.ts` + the canonical
 * pricing catalog. Edge functions cannot import from `src/`, so this script
 * snapshots the subset the agent needs into
 * `supabase/functions/_shared/muse/videoModelCatalog.ts`.
 *
 * Run: bun scripts/generate-muse-model-catalog.mjs
 */
import { writeFileSync } from 'node:fs';

const { VIDEO_MODEL_SPECS } = await import('../src/config/videoModelSpecs.ts');

const entries = [];
for (const spec of VIDEO_MODEL_SPECS) {
  if (!spec.available || spec.deprecated || spec.aliasOf) continue;
  const modes = {};
  for (const mode of spec.modes ?? []) {
    modes[mode.mode] = {
      durations: mode.durations ?? [],
      resolutions: (mode.resolutions ?? []).map((r) => ({
        label: r.label,
        pricingId: r.pricingId ?? r.catalogId ?? null,
      })),
      aspectRatios: mode.aspectRatios ?? [],
      audio: !!mode.audio,
      inputs: mode.inputs ?? {},
    };
  }
  entries.push({
    id: spec.id,
    displayName: spec.displayName,
    family: spec.family,
    provider: spec.provider,
    edgeFunction: spec.edgeFunction,
    uiGroup: spec.uiGroup,
    modes,
  });
}

const header = `// AUTO-GENERATED by scripts/generate-muse-model-catalog.mjs — do not edit by hand.
// Snapshot of src/config/videoModelSpecs.ts for the Deno edge runtime.
// Regenerate with: bun scripts/generate-muse-model-catalog.mjs

export interface MuseModeSpec {
  durations: number[];
  resolutions: { label: string; pricingId: string | null }[];
  aspectRatios: string[];
  audio: boolean;
  inputs: Record<string, unknown>;
}

export interface MuseModelSpec {
  id: string;
  displayName: string;
  family: string;
  provider: string;
  edgeFunction: string;
  uiGroup: string;
  modes: Record<string, MuseModeSpec>;
}

export const MUSE_VIDEO_MODELS: MuseModelSpec[] = ${JSON.stringify(entries, null, 2)};

export function getMuseModel(id: string): MuseModelSpec | undefined {
  return MUSE_VIDEO_MODELS.find((m) => m.id === id);
}
`;

writeFileSync('supabase/functions/_shared/muse/videoModelCatalog.ts', header);
console.log(`Wrote ${entries.length} models.`);
